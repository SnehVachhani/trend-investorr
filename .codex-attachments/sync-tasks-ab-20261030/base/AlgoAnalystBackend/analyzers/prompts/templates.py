SECTOR_ANALYSIS_PROMPT = """You are an Indian stock market sector analyst.
Analyze this sector's current momentum and provide a sentiment assessment.

## Sector: {sector_name}
- **Stocks Tracked**: {stocks_count}
- **Advancing**: {advancing} | **Declining**: {declining}
- **A/D Ratio**: {ad_ratio:.2f}
- **Avg Volume Ratio**: {avg_volume_ratio:.1f}x
- **Avg Price Change**: {avg_change_pct:+.2f}%
- **Heat Score**: {heat_score:.2f}/1.0

## Top Volume Movers in Sector
{top_movers}

## Rules
1. Respond ONLY with valid JSON
2. "sentiment" must be one of: "BULLISH", "BEARISH", "NEUTRAL"
3. "conviction" must be between 0.0 and 1.0

## Required JSON Response Format
{{
    "sentiment": "BULLISH|BEARISH|NEUTRAL",
    "conviction": 0.0-1.0,
    "reasoning": "Your sector analysis in 2-3 sentences",
    "key_drivers": ["driver1", "driver2"],
    "outlook": "SHORT_TERM|MEDIUM_TERM|LONG_TERM"
}}"""


def format_signal_prompt(
    signal: Any,
    indicators: dict[str, Any],
    candles: list[Any],
) -> str:
    """
    Format the signal validation prompt with real data.

    Args:
        signal: Signal dataclass.
        indicators: Dict from static analyzer (RSI, EMA, etc.).
        candles: Recent candle history.

    Returns:
        Formatted prompt string ready for Gemini.
    """
    # Format last 10 candles as a table
    recent = candles[-10:] if len(candles) >= 10 else candles
    price_lines = []
    for c in recent:
        date_str = c.timestamp.strftime("%Y-%m-%d")
        change = ((c.close - c.open) / c.open * 100) if c.open > 0 else 0
        price_lines.append(
            f"  {date_str} | O:{c.open:.2f} H:{c.high:.2f} L:{c.low:.2f} "
            f"C:{c.close:.2f} V:{c.volume:>10,} | {change:+.1f}%"
        )
    price_history = "\n".join(price_lines) if price_lines else "No recent data"

    return SIGNAL_VALIDATION_PROMPT.format(
        symbol=signal.symbol,
        signal_type=signal.signal_type.value,
        price=signal.price,
        volume_ratio=signal.volume_ratio,
        volume_current=signal.volume_current,
        volume_avg=signal.volume_avg,
        signal_score=signal.score,
        sector=signal.sector or "Unknown",
        # Trend
        rsi=indicators.get("rsi", "N/A"),
        ema_short=indicators.get("ema_short", "N/A"),
        ema_long=indicators.get("ema_long", "N/A"),
        sma_20=indicators.get("sma_20", "N/A"),
        sma_50=indicators.get("sma_50", "N/A"),
        sma_200=indicators.get("sma_200", "N/A"),
        supertrend=indicators.get("supertrend", "N/A"),
        supertrend_direction=_direction_label(indicators.get("supertrend_direction", 0)),
        # Momentum
        macd_line=indicators.get("macd_line", "N/A"),
        macd_signal=indicators.get("macd_signal", "N/A"),
        macd_histogram=indicators.get("macd_histogram", "N/A"),
        adx_14=indicators.get("adx_14", "N/A"),
        # Volatility
        atr_14=indicators.get("atr_14", "N/A"),
        bb_upper=indicators.get("bollinger_upper", "N/A"),
        bb_lower=indicators.get("bollinger_lower", "N/A"),
        bb_width=indicators.get("bollinger_width", "N/A"),
        # Structure
        pivot=indicators.get("pivot_point", "N/A"),
        s1=indicators.get("pivot_s1", "N/A"),
        s2=indicators.get("pivot_s2", "N/A"),
        r1=indicators.get("pivot_r1", "N/A"),
        r2=indicators.get("pivot_r2", "N/A"),
        support=indicators.get("support_level", "N/A"),
        resistance=indicators.get("resistance_level", "N/A"),
        # Microstructure
        vwap=indicators.get("vwap_proxy", indicators.get("vwap_daily", "N/A")),
        exchange_vwap=signal.metadata.get("exchange_vwap", "N/A"),
        buy_sell_ratio=signal.metadata.get("buy_sell_ratio", "N/A"),
        bid_ask_spread=signal.metadata.get("bid_ask_spread", "N/A"),
        gap_pct=signal.metadata.get("gap_pct", 0),
        delivery_pct=indicators.get("delivery_pct", 0),
        price_history=price_history,
    )


def _direction_label(direction: int) -> str:
    """Convert supertrend direction int to human label."""
    if direction == 1:
        return "Bullish ↑"
    elif direction == -1:
        return "Bearish ↓"
    return "Neutral"


def format_sector_prompt(sector_heat: Any) -> str:
    """
    Format the sector analysis prompt with real sector data.

    Args:
        sector_heat: SectorHeat dataclass.

    Returns:
        Formatted prompt string ready for Gemini.
    """
    movers = "\n".join(f"  - {sym}" for sym in sector_heat.top_movers[:10]) if sector_heat.top_movers else "  No data"

    return SECTOR_ANALYSIS_PROMPT.format(
        sector_name=sector_heat.sector_name,
        stocks_count=sector_heat.stocks_count,
        advancing=sector_heat.advancing,
        declining=sector_heat.declining,
        ad_ratio=sector_heat.advance_decline_ratio,
        avg_volume_ratio=sector_heat.avg_volume_ratio,
        avg_change_pct=sector_heat.avg_change_pct,
        heat_score=sector_heat.heat_score,
        top_movers=movers,
    )
