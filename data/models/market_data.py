"""
Trend-Investorr: Market Data Models

Immutable dataclasses for representing market data throughout the system.
All modules consume and produce these standardized models.

Models:
    - Stock: An instrument in the universe
    - Candle: OHLCV bar at any interval
    - Tick: Real-time price update from WebSocket
    - VolumeSnapshot: Point-in-time volume reading for spike detection
    - Signal: Trading signal generated by the engine
    - AnalysisResult: Output from any analyzer
    - OrderRequest / OrderResult: Trading order lifecycle
    - RiskDecision: Output from risk manager
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, date
from typing import Any

from core.constants import (
    AnalysisAction,
    CandleInterval,
    CompositeStrategy,
    Exchange,
    OrderStatus,
    OrderType,
    OrderVariety,
    ProductType,
    SignalSource,
    SignalStatus,
    SignalStrength,
    SignalType,
    TransactionType,
    IST,
)


# ── Instrument ───────────────────────────────────────────────


@dataclass(frozen=True)
class Stock:
    """An instrument in the tradable universe."""

    symbol: str                         # e.g., "RELIANCE"
    token: str                          # SmartAPI token (e.g., "2885")
    name: str                           # Full company name
    exchange: Exchange = Exchange.NSE
    series: str = "EQ"                  # EQ, BE, etc.
    sector: str = ""                    # Mapped sector name
    industry: str = ""                  # NSE industry classification
    market_cap_cr: float = 0.0          # Market cap in crores
    lot_size: int = 1                   # F&O lot size (1 for equity)

    @property
    def trading_symbol(self) -> str:
        """SmartAPI trading symbol format."""
        return f"{self.symbol}-{self.series}"

    def __str__(self) -> str:
        return f"{self.symbol} ({self.exchange.value})"


# ── Price Data ───────────────────────────────────────────────


@dataclass(frozen=True)
class Candle:
    """OHLCV candle at any time interval."""

    symbol: str
    timestamp: datetime
    open: float
    high: float
    low: float
    close: float
    volume: int
    interval: CandleInterval = CandleInterval.ONE_DAY

    # Optional enriched fields
    delivery_qty: int = 0
    delivery_pct: float = 0.0
    vwap: float = 0.0

    @property
    def body_size(self) -> float:
        """Absolute candle body size."""
        return abs(self.close - self.open)

    @property
    def is_bullish(self) -> bool:
        return self.close > self.open

    @property
    def is_bearish(self) -> bool:
        return self.close < self.open

    @property
    def range(self) -> float:
        """High - Low range."""
        return self.high - self.low

    @property
    def change_pct(self) -> float:
        """Percentage change from open to close."""
        if self.open == 0:
            return 0.0
        return ((self.close - self.open) / self.open) * 100


@dataclass(frozen=True)
class Tick:
    """
    Real-time price update from WebSocket.

    Received at high frequency during market hours.
    """

    symbol: str
    token: str
    ltp: float                          # Last Traded Price
    timestamp: datetime
    volume: int = 0
    open: float = 0.0
    high: float = 0.0
    low: float = 0.0
    close: float = 0.0                  # Previous day close
    change_pct: float = 0.0
    best_bid: float = 0.0
    best_ask: float = 0.0
    total_buy_qty: int = 0
    total_sell_qty: int = 0
    avg_trade_price: float = 0.0        # VWAP-like

    @property
    def spread(self) -> float:
        """Bid-ask spread."""
        if self.best_bid == 0:
            return 0.0
        return self.best_ask - self.best_bid


# ── Volume ───────────────────────────────────────────────────


@dataclass(frozen=True)
class VolumeSnapshot:
    """Point-in-time volume reading for spike detection."""

    symbol: str
    timestamp: datetime
    cumulative_volume: int              # Today's cumulative volume so far
    avg_volume_30d: int = 0             # 30-day average full-day volume
    avg_volume_90d: int = 0             # 90-day average full-day volume

    @property
    def volume_ratio_30d(self) -> float:
        """Current volume as a multiple of 30-day average."""
        if self.avg_volume_30d == 0:
            return 0.0
        return self.cumulative_volume / self.avg_volume_30d

    @property
    def volume_ratio_90d(self) -> float:
        """Current volume as a multiple of 90-day average."""
        if self.avg_volume_90d == 0:
            return 0.0
        return self.cumulative_volume / self.avg_volume_90d


# ── Signals ──────────────────────────────────────────────────


@dataclass
class Signal:
    """Trading signal generated by any scanner in the engine."""

    symbol: str
    token: str
    signal_type: SignalType
    strength: SignalStrength
    score: float                        # 0.0 - 1.0 composite score
    price: float                        # Price at signal generation
    source: SignalSource = SignalSource.VOLUME_SPIKE  # Which scanner originated this
    sector: str = ""
    volume_current: int = 0
    volume_avg: int = 0
    volume_ratio: float = 0.0
    status: SignalStatus = SignalStatus.PENDING
    created_at: datetime = field(default_factory=lambda: datetime.now(IST))
    metadata: dict[str, Any] = field(default_factory=dict)

    @property
    def volume_spike_x(self) -> str:
        """Human-readable volume spike multiplier."""
        return f"{self.volume_ratio:.1f}x"



# ── Observations (scanner outputs — raw facts, NOT trade decisions) ───


@dataclass
class Observation:
    """
    A raw observation from a scanner. This is a FACT, not a trade decision.

    Scanners detect patterns and emit Observations. The StrategyEngine
    collects these and decides whether to trade.

    Example: "RELIANCE broke above resistance ₹2,850" is an observation.
             "BUY RELIANCE" is a trade decision (made by StrategyEngine).
    """

    symbol: str
    token: str
    source: SignalSource               # Which scanner emitted this
    direction: str                     # "bullish" or "bearish"
    confidence: float                  # 0.0 - 1.0 how confident the scanner is
    price: float                       # Price at observation time
    pattern_name: str = ""             # e.g. "resistance_breakout", "rsi_oversold"
    timestamp: datetime = field(default_factory=lambda: datetime.now(IST))
    details: dict[str, Any] = field(default_factory=dict)


@dataclass
class TradeDecision:
    """
    A trade decision from the StrategyEngine.

    Only created when multiple scanners agree (confluence).
    This is the ONLY object that should trigger order execution.
    """

    symbol: str
    token: str
    direction: str                     # "BUY" or "SELL"
    confluence_score: float            # Weighted score across all agreeing scanners
    contributing_sources: list[SignalSource] = field(default_factory=list)
    observations: list[Observation] = field(default_factory=list)
    timestamp: datetime = field(default_factory=lambda: datetime.now(IST))
    metadata: dict[str, Any] = field(default_factory=dict)

    @property
    def scanner_count(self) -> int:
        """Number of unique scanners that contributed."""
        return len(set(self.contributing_sources))


# ── Analysis ─────────────────────────────────────────────────


@dataclass(frozen=True)
class AnalysisResult:
    """
    Output from any SignalAnalyzer implementation.

    Every analyzer (static, Gemini, composite) returns this same structure.
    """

    action: AnalysisAction              # BUY / SELL / SKIP / HOLD
    confidence: float                   # 0.0 - 1.0
    reasoning: str                      # Human-readable explanation
    analyzer_name: str                  # Which analyzer produced this
    signal_symbol: str = ""             # The stock being analyzed
    indicators: dict[str, Any] = field(default_factory=dict)  # RSI, EMA, etc.
    raw_response: str = ""              # Raw AI response (Gemini only)

    @property
    def is_actionable(self) -> bool:
        """True if the analysis recommends taking action."""
        return self.action in (AnalysisAction.BUY, AnalysisAction.SELL)

    @property
    def confidence_pct(self) -> str:
        return f"{self.confidence * 100:.0f}%"


# ── Trading ──────────────────────────────────────────────────


@dataclass
class OrderRequest:
    """Order to be placed — validated by risk manager before execution."""

    symbol: str
    token: str
    transaction_type: TransactionType
    quantity: int
    order_type: OrderType = OrderType.MARKET
    product_type: ProductType = ProductType.INTRADAY
    variety: OrderVariety = OrderVariety.NORMAL
    price: float = 0.0                  # For LIMIT orders
    trigger_price: float = 0.0          # For STOP_LOSS orders
    exchange: Exchange = Exchange.NSE
    signal_id: int | None = None        # Link to originating signal

    @property
    def trading_symbol(self) -> str:
        return f"{self.symbol}-EQ"

    @property
    def estimated_value(self) -> float:
        return self.price * self.quantity if self.price > 0 else 0.0


@dataclass
class OrderResult:
    """Result of an order placement — from broker or paper trader."""

    success: bool
    order_id: str = ""                  # Internal order ID
    broker_order_id: str = ""           # Broker's order ID
    status: OrderStatus = OrderStatus.CREATED
    filled_qty: int = 0
    avg_fill_price: float = 0.0
    message: str = ""
    is_paper: bool = False
    timestamp: datetime = field(default_factory=lambda: datetime.now(IST))

    @property
    def slippage(self) -> float:
        """Slippage percentage (only meaningful after fill)."""
        return 0.0  # Calculated by order manager after comparing with signal price


@dataclass(frozen=True)
class RiskDecision:
    """Output from risk manager — approve or reject a trade."""

    approved: bool
    quantity: int                        # Approved quantity (may be less than requested)
    reason: str                          # Why approved/rejected
    max_position_value: float = 0.0      # Max ₹ value for this position
    stop_loss_price: float = 0.0         # Suggested stop loss
    target_price: float = 0.0            # Suggested target


# ── Portfolio ────────────────────────────────────────────────


@dataclass
class Position:
    """A current open position (live or paper)."""

    symbol: str
    token: str
    quantity: int
    avg_buy_price: float
    current_price: float = 0.0
    product_type: ProductType = ProductType.INTRADAY
    is_paper: bool = False
    opened_at: datetime = field(default_factory=lambda: datetime.now(IST))

    @property
    def unrealized_pnl(self) -> float:
        return (self.current_price - self.avg_buy_price) * self.quantity

    @property
    def unrealized_pnl_pct(self) -> float:
        if self.avg_buy_price == 0:
            return 0.0
        return ((self.current_price - self.avg_buy_price) / self.avg_buy_price) * 100

    @property
    def current_value(self) -> float:
        return self.current_price * self.quantity

    @property
    def invested_value(self) -> float:
        return self.avg_buy_price * self.quantity


@dataclass(frozen=True)
class DailyPnL:
    """Daily profit and loss summary."""

    date: date
    realized_pnl: float = 0.0
    unrealized_pnl: float = 0.0
    total_trades: int = 0
    winning_trades: int = 0
    losing_trades: int = 0
    max_drawdown: float = 0.0
    is_paper: bool = False

    @property
    def total_pnl(self) -> float:
        return self.realized_pnl + self.unrealized_pnl

    @property
    def win_rate(self) -> float:
        if self.total_trades == 0:
            return 0.0
        return (self.winning_trades / self.total_trades) * 100


# ── Technical Indicators ─────────────────────────────────────


@dataclass
class TechnicalIndicators:
    """
    Computed technical indicators for a single stock on a single date.

    Populated by IndicatorEngine.compute_all() from daily candle data,
    stored in the technical_indicators table, and loaded into memory
    at 9:00 AM warm-up for zero-latency hot path access.
    """

    stock_id: int
    date: date

    # ── Trend Indicators ──
    sma_20: float = 0.0                 # Simple Moving Average (20 period)
    sma_50: float = 0.0                 # SMA (50)
    sma_200: float = 0.0                # SMA (200) — long-term trend
    ema_20: float = 0.0                 # Exponential Moving Average (20)
    ema_50: float = 0.0                 # EMA (50)
    supertrend: float = 0.0             # Supertrend value
    supertrend_direction: int = 0       # 1 = bullish, -1 = bearish

    # ── Momentum Indicators ──
    rsi_14: float = 50.0                # Relative Strength Index (14)
    rsi_10: float = 50.0                # Relative Strength Index (10)
    macd_line: float = 0.0              # MACD line (EMA12 - EMA26)
    macd_signal: float = 0.0            # MACD signal line (EMA9 of MACD)
    macd_histogram: float = 0.0         # MACD histogram (MACD - Signal)
    adx_14: float = 0.0                 # Average Directional Index (14)

    # ── Volatility Indicators ──
    atr_14: float = 0.0                 # Average True Range (14)
    bollinger_upper: float = 0.0        # Bollinger upper band (SMA20 + 2σ)
    bollinger_lower: float = 0.0        # Bollinger lower band (SMA20 - 2σ)
    bollinger_width: float = 0.0        # Band width (upper - lower) / SMA20

    # ── Volume Indicators ──
    obv: int = 0                        # On-Balance Volume
    vwap_daily: float = 0.0             # Daily VWAP
    delivery_pct: float = 0.0           # Delivery % from bhavcopy

    # ── Price Structure ──
    pivot_point: float = 0.0            # Classic pivot point
    pivot_r1: float = 0.0               # Resistance 1
    pivot_r2: float = 0.0               # Resistance 2
    pivot_s1: float = 0.0               # Support 1
    pivot_s2: float = 0.0               # Support 2
    support_level: float = 0.0          # Swing-low support
    resistance_level: float = 0.0       # Swing-high resistance
    high_52w: float = 0.0               # 52-week high
    low_52w: float = 0.0                # 52-week low

    @property
    def is_bullish_trend(self) -> bool:
        """Price above all major MAs and Supertrend bullish."""
        return self.supertrend_direction == 1

    @property
    def is_overbought(self) -> bool:
        return self.rsi_14 > 70

    @property
    def is_oversold(self) -> bool:
        return self.rsi_14 < 30

    @property
    def is_trending(self) -> bool:
        """ADX > 25 indicates a strong trend (up or down)."""
        return self.adx_14 > 25.0

    @property
    def macd_bullish(self) -> bool:
        """MACD line above signal line."""
        return self.macd_histogram > 0

    def to_dict(self) -> dict[str, Any]:
        """Convert to dict for signal metadata or DB storage."""
        return {
            "sma_20": self.sma_20, "sma_50": self.sma_50, "sma_200": self.sma_200,
            "ema_20": self.ema_20, "ema_50": self.ema_50,
            "supertrend": self.supertrend, "supertrend_direction": self.supertrend_direction,
            "rsi_14": self.rsi_14,
            "macd_line": self.macd_line, "macd_signal": self.macd_signal,
            "macd_histogram": self.macd_histogram, "adx_14": self.adx_14,
            "atr_14": self.atr_14,
            "bollinger_upper": self.bollinger_upper, "bollinger_lower": self.bollinger_lower,
            "bollinger_width": self.bollinger_width,
            "obv": self.obv, "vwap_daily": self.vwap_daily, "delivery_pct": self.delivery_pct,
            "pivot_point": self.pivot_point,
            "pivot_r1": self.pivot_r1, "pivot_r2": self.pivot_r2,
            "pivot_s1": self.pivot_s1, "pivot_s2": self.pivot_s2,
            "support_level": self.support_level, "resistance_level": self.resistance_level,
            "high_52w": self.high_52w, "low_52w": self.low_52w,
        }

