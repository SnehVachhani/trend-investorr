"""
Trend-Investorr: Abstract Signal Analyzer Interface

Strategy Pattern base class. All analyzers implement this interface,
allowing the system to swap between static rules, AI, or composite
strategies without changing any downstream code.

Interface:
    analyze(signal, candles) → AnalysisResult
    health_check() → bool
    name → str

Implementations:
    StaticRuleAnalyzer  — RSI, EMA, VWAP rule-based (no AI, no API keys)
    GeminiAnalyzer      — Gemini AI-powered validation (needs API key)
    CompositeAnalyzer   — Chains multiple analyzers with voting strategy
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Any

from data.models.market_data import AnalysisResult, Candle, Signal


class SignalAnalyzer(ABC):
    """
    Abstract base class for all signal analyzers.

    Every analyzer takes a Signal (from the signal generator) and
    historical candle data, then returns an AnalysisResult with:
        - action: BUY / SELL / SKIP / HOLD
        - confidence: 0.0 - 1.0
        - reasoning: human-readable explanation
        - indicators: dict of computed indicators (RSI, EMA, etc.)

    Contract:
        - analyze() MUST NOT raise exceptions — return SKIP on failure
        - analyze() MUST complete within 30 seconds
        - health_check() returns False if the analyzer can't function
    """

    @abstractmethod
    def analyze(self, signal: Signal, candles: list[Candle]) -> AnalysisResult:
        """
        Analyze a trading signal and return a validation result.

        Args:
            signal: The Signal generated by the signal generator.
            candles: Recent historical candles for the stock
                     (typically 30-90 days of daily candles).

        Returns:
            AnalysisResult with action, confidence, reasoning.
            On any internal error, return action=SKIP with explanation.
        """
        ...

    @abstractmethod
    def health_check(self) -> bool:
        """
        Check if the analyzer is operational.

        Returns:
            True if the analyzer can process signals.
            False if it's degraded (e.g., API key missing, service down).
        """
        ...

    @property
    @abstractmethod
    def name(self) -> str:
        """Unique name identifying this analyzer (e.g., 'static', 'gemini')."""
        ...

    def __repr__(self) -> str:
        return f"{self.__class__.__name__}(name='{self.name}', healthy={self.health_check()})"
